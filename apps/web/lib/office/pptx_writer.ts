function slideXml(width: number, height: number): string {
  const scale = Math.min(SLIDE_WIDTH_EMU / width, SLIDE_HEIGHT_EMU / height);
  const cx = Math.round(width * scale);
  const cy = Math.round(height * scale);
  const x = Math.round((SLIDE_WIDTH_EMU - cx) / 2);
  const y = Math.round((SLIDE_HEIGHT_EMU - cy) / 2);

  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<p:sld xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships" xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main">
  <p:cSld>
    <p:spTree>
      <p:nvGrpSpPr><p:cNvPr id="1" name=""/><p:cNvGrpSpPr/><p:nvPr/></p:nvGrpSpPr>
      <p:grpSpPr/>
      <p:pic>
        <p:nvPicPr><p:cNvPr id="2" name="Page"/><p:cNvPicPr><a:picLocks noChangeAspect="1"/></p:cNvPicPr><p:nvPr/></p:nvPicPr>
        <p:blipFill><a:blip r:embed="rId1"/><a:stretch><a:fillRect/></a:stretch></p:blipFill>
        <p:spPr><a:xfrm><a:off x="${x}" y="${y}"/><a:ext cx="${cx}" cy="${cy}"/></a:xfrm><a:prstGeom prst="rect"><a:avLst/></a:prstGeom></p:spPr>
      </p:pic>
    </p:spTree>
  </p:cSld>
</p:sld>`;
}

function slideRels(index: number): string {
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/image" Target="../media/image${index + 1}.jpeg"/>
</Relationships>`;
}

/** Builds a minimal but valid .pptx with one full-bleed picture per slide — a PDF page's text
 * is not editable in the result, the same trade-off `lib/pdf/redact_pdf.ts` makes for the pages
 * it flattens. Rebuilding real editable shapes and text boxes from a PDF's content stream would
 * need to reconstruct font, size and position for every run, which is a different and much
 * larger project than this tool's honest scope. Requires the full slideMaster/slideLayout/theme
 * relationship chain — PowerPoint opens a file missing any of them with a repair prompt. */
export async function buildPptx(images: readonly SlideImage[]): Promise<Uint8Array> {
  if (images.length === 0) throw new Error('At least one page is required.');

  const files: Record<string, string | Uint8Array> = {
    '[Content_Types].xml': contentTypes(images.length),
    '_rels/.rels': ROOT_RELS,
    'ppt/presentation.xml': presentationXml(images.length),
    'ppt/_rels/presentation.xml.rels': presentationRels(images.length),
    'ppt/slideMasters/slideMaster1.xml': SLIDE_MASTER,
    'ppt/slideMasters/_rels/slideMaster1.xml.rels': SLIDE_MASTER_RELS,
    'ppt/slideLayouts/slideLayout1.xml': SLIDE_LAYOUT,
    'ppt/slideLayouts/_rels/slideLayout1.xml.rels': SLIDE_LAYOUT_RELS,
    'ppt/theme/theme1.xml': THEME,
  };

  images.forEach((image, index) => {
    files[`ppt/slides/slide${index + 1}.xml`] = slideXml(image.width, image.height);
    files[`ppt/slides/_rels/slide${index + 1}.xml.rels`] = slideRels(index);
    files[`ppt/media/image${index + 1}.jpeg`] = image.bytes;
  });

  return writeOoxmlPackage(files);
}
